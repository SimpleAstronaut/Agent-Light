"""以独立 Python 实现生成 USB v1 黄金向量。

版本：1.0.0（固件工具基线）；日期：2026-10-28。
用法：py -3.14 firmware/tools/protocol_reference.py --check 只核对；
不带 --check 时覆盖 contracts/usb-vectors.json 和 tests/host/usb_vectors.inc。
依赖：仅 Python 标准库；CRC 使用 binascii，避免直接复制固件算法。
"""
import argparse
import binascii
import json
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[2]


def encode(raw: bytes) -> bytes:
    """编码标准 COBS 并追加单字节 0 分隔符。

    Args:
        raw: bytes 原始数据，支持空输入及超过单帧的长度，不修改输入。
    Returns:
        新的 bytes，包含帧尾 0；本函数不附加头或 CRC。
    """
    output = bytearray()
    for block in raw.split(b"\0"):
        while len(block) >= 254:
            output.append(255)
            output.extend(block[:254])
            block = block[254:]
        output.append(len(block) + 1)
        output.extend(block)
    return bytes(output) + b"\0"


def decode(wire: bytes) -> bytes:
    """移除末尾分隔符并解码单个 COBS 帧。

    Args:
        wire: bytes，必须包含末尾 0；不校验协议版本/长度或 CRC。
    Returns:
        解码后的新 bytes；wire=b"\0" 也返回空串，协议层另判最小长度。
    Raises:
        ValueError: 缺分隔符、零长度码、段越界或编码段包含 0。
    """
    if not wire or wire[-1] != 0:
        raise ValueError("missing delimiter")
    encoded = wire[:-1]
    output = bytearray()
    offset = 0
    while offset < len(encoded):
        code = encoded[offset]
        offset += 1
        if code == 0 or offset + code - 1 > len(encoded):
            raise ValueError("invalid COBS")
        block = encoded[offset:offset + code - 1]
        if 0 in block:
            raise ValueError("embedded delimiter")
        output.extend(block)
        offset += code - 1
        if code != 255 and offset < len(encoded):
            output.append(0)
    return bytes(output)


def frame(command: int, seq: int, payload=b"", version=1) -> bytes:
    """组装协议 raw，CRC 覆盖四字节头和负载，结果按小端追加。

    Args:
        command: uint8_t 命令/响应类型。
        seq: uint8_t 事务序号。
        payload: bytes 负载，默认空；本工具不强制协议的 32 字节上限。
        version: uint8_t 协议版本，默认 1，可构造不支持版本的负面向量。
    Returns:
        不含 COBS/分隔符的 raw bytes。
    Raises:
        ValueError: 任一头字段或负载长度不能装入 uint8_t。
    """
    header = bytes([version, command, seq, len(payload)]) + payload
    return header + struct.pack("<H", binascii.crc_hqx(header, 0xffff))


def vectors():
    """生成 17 组互相独立的成功/拒绝/静默丢弃黄金向量。

    无参数；返回 list[dict]，各字典含 name/raw/wire/response 的十六进制字符串。
    预期状态从初始化后 300 ms WAIT_SYNC 起算；空 response 表示应静默丢弃。
    """
    cases = []
    def add(name, raw, reply):
        """把一组原始请求与预期响应追加到外层 cases。

        Args:
            name: 向量名称字符串。
            raw: 请求 raw bytes。
            reply: 响应 raw bytes，None/空值表示无响应。
        Returns:
            None；写入 cases 的十六进制数据为副本，不保留可变输入。
        """
        cases.append(dict(name=name, raw=raw.hex(), wire=encode(raw).hex(),
                          response=encode(reply).hex() if reply else ""))
    for state in range(5):
        payload = struct.pack("<IBB", 0x12345678, state, 35)
        add(f"set_state_{state}", frame(1, 9, payload),
            frame(0x81, 9, b"\1\0" + struct.pack("<I", 0x12345678) + b"\1"))
    add("heartbeat", frame(2, 10), frame(0x81, 10, b"\2\0\0\0\0\0"))
    status = struct.pack("<BBIBBBHIH", 1, 255, 0, 0, 35, 11, 0x100, 0, 0)
    add("status", frame(3, 11), frame(0x83, 11, status))
    for name, cmd, payload, version, error in [
        ("short_set", 1, b"\0" * 5, 1, 1),
        ("long_heartbeat", 2, b"\0", 1, 1),
        ("unknown", 0x40, b"", 1, 2),
        ("version", 2, b"", 2, 3),
        ("bad_state", 1, struct.pack("<IBB", 1, 5, 35), 1, 4),
        ("low_brightness", 1, struct.pack("<IBB", 1, 1, 19), 1, 4),
        ("high_brightness", 1, struct.pack("<IBB", 1, 1, 101), 1, 4),
    ]:
        add(name, frame(cmd, 12, payload, version),
            frame(0x82, 12, bytes([cmd, error])))
    bad = bytearray(frame(2, 13)); bad[-1] ^= 0x80
    add("bad_crc_silent", bytes(bad), None)
    add("truncated_silent", frame(2, 14)[:-1], None)
    # raw 声明长度与实际不符，即便 CRC 正确也必须静默丢弃。
    malformed = bytes([1, 2, 15, 1])
    malformed += struct.pack("<H", binascii.crc_hqx(malformed, 0xffff))
    add("structural_length_silent", malformed, None)
    return cases


def main():
    """生成参考内容并按 --check 选择只读核验或覆盖写入。

    无参数；从命令行读取选项。成功打印向量数量并返回 None。
    --check 遇到文件内容不一致触发 AssertionError；缺文件或写入错误直接传播。
    """
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    assert binascii.crc_hqx(b"123456789", 0xffff) == 0x29b1
    cases = vectors()
    json_text = json.dumps(dict(protocol=1, vectors=cases), indent=2) + "\n"
    lines = ["// Generated by tools/protocol_reference.py; do not edit.",
             "static const struct { const char *name, *wire, *response; }",
             "    kVectors[] = {"]
    for case in cases:
        lines.append('  {"%(name)s", "%(wire)s", "%(response)s"},' % case)
    lines.append("};\n")
    files = {ROOT / "contracts/usb-vectors.json": json_text,
             ROOT / "firmware/tests/host/usb_vectors.inc": "\n".join(lines)}
    for path, content in files.items():
        if args.check:
            assert path.read_text(encoding="utf-8") == content, f"stale {path}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    print(f"PASS: {len(cases)} independent Python golden vectors")


if __name__ == "__main__":
    main()
